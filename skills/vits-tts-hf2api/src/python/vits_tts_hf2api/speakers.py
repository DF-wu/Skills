def _build_gradio_name_map():
    """Match SPEAKERS keys to GRADIO_SPEAKER_CHOICES entries."""
    result = {}
    for short_name in SPEAKERS:
        if short_name in GRADIO_SPEAKER_CHOICES:
            result[short_name] = short_name
            continue
        for gc in GRADIO_SPEAKER_CHOICES:
            if gc.startswith(short_name) and len(short_name) >= 2:
                result[short_name] = gc
                break
    return result


GRADIO_NAME_MAP = _build_gradio_name_map()


def resolve_speaker_gradio(name: str) -> str:
    """Resolve a speaker name/alias to the actual Gradio dropdown value."""
    if not name:
        return GRADIO_SPEAKER_CHOICES[0]
    if name in GRADIO_SPEAKER_CHOICES:
        return name
    if name in GRADIO_NAME_MAP:
        return GRADIO_NAME_MAP[name]
    if name.lower() in SPEAKER_ALIASES:
        resolved = SPEAKER_ALIASES[name.lower()]
        if resolved in GRADIO_NAME_MAP:
            return GRADIO_NAME_MAP[resolved]
        if resolved in GRADIO_SPEAKER_CHOICES:
            return resolved
    lower = name.lower()
    for gc in GRADIO_SPEAKER_CHOICES:
        if gc.lower() == lower:
            return gc
    for gc in GRADIO_SPEAKER_CHOICES:
        if gc.lower().startswith(lower) and len(lower) >= 2:
            return gc
    for gc in GRADIO_SPEAKER_CHOICES:
        if lower in gc.lower():
            return gc
    return name


_DEFAULT_SPEAKER_ID = SPEAKERS.get(config.DEFAULT_SPEAKER, 0)


def resolve_speaker(name: str) -> int:
    if not name:
        return _DEFAULT_SPEAKER_ID
    if name in SPEAKERS:
        return SPEAKERS[name]
    if name.lower() in SPEAKER_ALIASES:
        resolved = SPEAKER_ALIASES[name.lower()]
        return SPEAKERS.get(resolved, _DEFAULT_SPEAKER_ID)
    # Try case-insensitive exact match among speakers
    lower = name.lower()
    for k, v in SPEAKERS.items():
        if k.lower() == lower:
            return v
    # Fallback to default
    return _DEFAULT_SPEAKER_ID


def resolve_vits_model_speaker(name: str) -> dict | None:
    if not name:
        return None
    if name in VITS_MODELS_SPEAKERS:
        return VITS_MODELS_SPEAKERS[name]
    lower = name.lower()
    if lower in VITS_MODELS_ALIASES:
        return VITS_MODELS_SPEAKERS.get(VITS_MODELS_ALIASES[lower])
    for key, info in VITS_MODELS_SPEAKERS.items():
        if info["canonical"] == name or info["canonical"].lower() == lower:
            return info
    if lower in SPEAKER_ALIASES:
        resolved = SPEAKER_ALIASES[lower]
        for key, info in VITS_MODELS_SPEAKERS.items():
            if info["canonical"] == resolved:
                return info
    return None


def search_speakers(query: str) -> list[dict]:
    q = query.lower()
    results: list[dict] = []
    seen_ids = set()
    for k, v in SPEAKERS.items():
        if q in k.lower() and v not in seen_ids:
            results.append({"id": v, "name": k})
            seen_ids.add(v)
    for alias, canonical in SPEAKER_ALIASES.items():
        if q in alias.lower():
            v = SPEAKERS.get(canonical)
            if v is not None and v not in seen_ids:
                results.append({"id": v, "name": canonical})
                seen_ids.add(v)
    return results
